function createKeyMaskViewPlugin(plugin) {
  return import_view2.ViewPlugin.fromClass(
    class {
      decorations;
      plugin;
      constructor(view) {
        this.plugin = plugin;
        this.decorations = this.buildDecorations(view);
      }
      update(update) {
        if (update.docChanged || update.viewportChanged) {
          this.decorations = this.buildDecorations(update.view);
        }
      }
      buildDecorations(view) {
        const builder = new import_state.RangeSetBuilder();
        const doc = view.state.doc;
        for (const { from, to } of view.visibleRanges) {
          const startLine = doc.lineAt(from);
          const endLine = doc.lineAt(to);
          const scanFrom = startLine.from;
          const scanTo = endLine.to;
          const text = doc.sliceString(scanFrom, scanTo);
          INLINE_SECRET_REGEX.lastIndex = 0;
          let match;
          while ((match = INLINE_SECRET_REGEX.exec(text)) !== null) {
            const matchFrom = scanFrom + match.index;
            const matchTo = matchFrom + match[0].length;
            const rawText = match[0];
            const payload = parseInline(rawText);
            builder.add(
              matchFrom,
              matchTo,
              import_view2.Decoration.replace({
                widget: new KeyMaskPillWidget({
                  plugin: this.plugin,
                  payload,
                  rawText,
                  isCodeBlock: false
                })
              })
            );
          }
        }
        return builder.finish();
      }
      destroy() {
      }
    },
    {
      decorations: (v) => v.decorations
    }
  );
}

// src/editor/postProcessor.ts
function registerPostProcessors(plugin) {
  const handleCodeBlock = (tag) => {
    return (source, el, ctx) => {
      const rawText = `\`\`\`${tag}
${source.trim()}
\`\`\``;
      const payload = parseCodeBlock(rawText);
      const pillEl = createPillElement({
        plugin,
        payload,
        rawText,
        isCodeBlock: true,
        sourcePath: ctx.sourcePath
      });
      el.empty();
      el.appendChild(pillEl);
    };
  };
  plugin.registerMarkdownCodeBlockProcessor("keymask", handleCodeBlock("keymask"));
  plugin.registerMarkdownCodeBlockProcessor("vaultguard", handleCodeBlock("vaultguard"));
  plugin.registerMarkdownPostProcessor(
    (el, ctx) => {
      const doc = el.ownerDocument;
      const walker = doc.createTreeWalker(el, NodeFilter.SHOW_TEXT);
      const nodesToReplace = [];
      let currentNode = walker.nextNode();
      while (currentNode) {
        const textNode = currentNode;
        if (textNode.nodeValue && (textNode.nodeValue.includes("%%km:v1:") || textNode.nodeValue.includes("%%vg:v1:"))) {
          nodesToReplace.push({ node: textNode, text: textNode.nodeValue });
        }
        currentNode = walker.nextNode();
      }
      for (const { node, text } of nodesToReplace) {
        INLINE_SECRET_REGEX.lastIndex = 0;
        let lastIndex = 0;
        let match;
        const fragments = [];
        while ((match = INLINE_SECRET_REGEX.exec(text)) !== null) {
          if (match.index > lastIndex) {
            fragments.push(doc.createTextNode(text.slice(lastIndex, match.index)));
          }
          const rawToken = match[0];
          const payload = parseInline(rawToken);
          const pill = createPillElement({
            plugin,
            payload,
            rawText: rawToken,
            isCodeBlock: false
          });
          fragments.push(pill);
          lastIndex = INLINE_SECRET_REGEX.lastIndex;
        }
        if (lastIndex < text.length) {
          fragments.push(doc.createTextNode(text.slice(lastIndex)));
        }
        if (fragments.length > 0 && node.parentNode) {
          for (const frag of fragments) {
            node.parentNode.insertBefore(frag, node);
          }
          node.parentNode.removeChild(node);
        }
      }
    }
  );
}

