var VaultGuardClipboard = class {
  static activeWipeTimer = null;
  static lastSecretCopied = null;
  /**
   * Safely obtain Electron clipboard module if running in Obsidian Desktop
   */
  static getElectronClipboard() {
    try {
      if (typeof window !== "undefined" && window.require) {
        const electron = window.require("electron");
        return electron?.clipboard || null;
      }
    } catch (e) {
    }
    return null;
  }
  /**
   * Reads current text from clipboard
   */
  static async readText() {
    const electronClipboard = this.getElectronClipboard();
    if (electronClipboard) {
      try {
        return electronClipboard.readText();
      } catch {
      }
    }
    if (typeof navigator !== "undefined" && navigator.clipboard && navigator.clipboard.readText) {
      try {
        return await navigator.clipboard.readText();
      } catch {
      }
    }
    return null;
  }
  /**
   * Overwrite clipboard with empty string
   */
  static async clearClipboard() {
    const electronClipboard = this.getElectronClipboard();
    if (electronClipboard) {
      try {
        electronClipboard.clear();
        return;
      } catch {
      }
    }
    if (typeof navigator !== "undefined" && navigator.clipboard && navigator.clipboard.writeText) {
      try {
        await navigator.clipboard.writeText("");
      } catch {
      }
    }
  }
  /**
   * Write sensitive secret to clipboard with volatile exclusion flags
   * and schedule ephemeral auto-wipe.
   */
  static async writeSecret(secret, options = {}) {
    const timeoutSeconds = options.timeoutSeconds ?? 30;
    const notifyOnWipe = options.notifyOnWipe ?? true;
    if (this.activeWipeTimer !== null) {
      clearTimeout(this.activeWipeTimer);
      this.activeWipeTimer = null;
    }
    this.lastSecretCopied = secret;
    const electronClipboard = this.getElectronClipboard();
    let writtenViaElectron = false;
    if (electronClipboard) {
      try {
        electronClipboard.writeText(secret);
        const isMac = typeof process !== "undefined" && process.platform === "darwin";
        const isWin = typeof process !== "undefined" && process.platform === "win32";
        const BufferClass = typeof Buffer !== "undefined" ? Buffer : window.require ? window.require("buffer").Buffer : null;
        if (BufferClass) {
          const emptyBuffer = BufferClass.from("");
          if (isMac) {
            electronClipboard.writeBuffer(
              "org.nspasteboard.ConcealedType",
              emptyBuffer
            );
            electronClipboard.writeBuffer(
              "org.nspasteboard.AutoGeneratedType",
              emptyBuffer
            );
          } else if (isWin) {
            electronClipboard.writeBuffer(
              "ExcludeClipboardContentFromMonitorProcessing",
              emptyBuffer
            );
          }
        }
        writtenViaElectron = true;
      } catch (err) {
        console.warn("VaultGuard: Electron clipboard flags failed, falling back to navigator", err);
      }
    }
    if (!writtenViaElectron) {
      if (typeof navigator !== "undefined" && navigator.clipboard && navigator.clipboard.writeText) {
        await navigator.clipboard.writeText(secret);
      } else {
        throw new Error("Unable to access clipboard in this environment.");
      }
    }
    if (timeoutSeconds > 0) {
      this.activeWipeTimer = setTimeout(async () => {
        try {
          const currentText = await this.readText();
          if (currentText === this.lastSecretCopied || currentText === null) {
            await this.clearClipboard();
            this.lastSecretCopied = null;
            if (notifyOnWipe) {
              new import_obsidian6.Notice("\u{1F512} VaultGuard: Ephemeral clipboard cleared for security.");
            }
          }
        } catch (e) {
          console.warn("VaultGuard: Ephemeral clipboard wipe encountered error:", e);
        } finally {
          this.activeWipeTimer = null;
        }
      }, timeoutSeconds * 1e3);
    }
  }
  /**
   * Cancel active auto-wipe timer
   */
  static cancelAutoWipe() {
    if (this.activeWipeTimer !== null) {
      clearTimeout(this.activeWipeTimer);
      this.activeWipeTimer = null;
      this.lastSecretCopied = null;
    }
  }
};

