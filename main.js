var CANARY_PLAINTEXT = "KEYMASK_CANARY_V1";
var LEGACY_CANARY_PLAINTEXT = "VAULTGUARD_CANARY_V1";
var DEFAULT_KDF_ITERATIONS = 6e5;
var AES_KEY_LENGTH = 256;
var AES_TAG_LENGTH = 128;
var IV_LENGTH_BYTES = 12;
var SALT_LENGTH_BYTES = 16;
function getCrypto() {
  if (typeof window !== "undefined" && window.crypto) {
    return window.crypto;
  }
  if (typeof crypto !== "undefined") {
    return crypto;
  }
  throw new Error("Web Cryptography API is not available.");
}
function getSubtleCrypto() {
  const cryptoObj = getCrypto();
  if (cryptoObj.subtle) {
    return cryptoObj.subtle;
  }
  throw new Error("Web Cryptography API (crypto.subtle) is not available in this environment.");
}
function generateSalt() {
  const salt = new Uint8Array(SALT_LENGTH_BYTES);
  getCrypto().getRandomValues(salt);
  return salt;
}
function generateIV() {
  const iv = new Uint8Array(IV_LENGTH_BYTES);
  getCrypto().getRandomValues(iv);
  return iv;
}
async function deriveKeyFromPassphrase(passphrase, salt, iterations = DEFAULT_KDF_ITERATIONS) {
  if (!passphrase) {
    throw new Error("Passphrase cannot be empty.");
  }
  if (salt.byteLength < SALT_LENGTH_BYTES) {
    throw new Error(`Salt must be at least ${SALT_LENGTH_BYTES} bytes.`);
  }
  if (iterations < 1e5) {
    throw new Error("KDF iterations too low. Minimum is 100,000 (recommended >= 600,000).");
  }
  const subtle = getSubtleCrypto();
  const encoder = new TextEncoder();
  const passphraseBytes = encoder.encode(passphrase);
  const baseKey = await subtle.importKey(
    "raw",
    passphraseBytes,
    "PBKDF2",
    false,
    ["deriveKey"]
  );
  const derivedKey = await subtle.deriveKey(
    {
      name: "PBKDF2",
      salt,
      iterations,
      hash: "SHA-256"
    },
    baseKey,
    {
      name: "AES-GCM",
      length: AES_KEY_LENGTH
    },
    false,
    // extractable: false (strictly non-extractable in memory)
    ["encrypt", "decrypt"]
  );
  return derivedKey;
}
async function encrypt(plaintext, key, customIV) {
  const subtle = getSubtleCrypto();
  const encoder = new TextEncoder();
  const plaintextBytes = encoder.encode(plaintext);
  const iv = customIV ?? generateIV();
  const encryptedBuffer = await subtle.encrypt(
    {
      name: "AES-GCM",
      iv,
      tagLength: AES_TAG_LENGTH
    },
    key,
    plaintextBytes
  );
  const encryptedBytes = new Uint8Array(encryptedBuffer);
  const tagLengthBytes = AES_TAG_LENGTH / 8;
  const dataLength = encryptedBytes.byteLength - tagLengthBytes;
  const data = encryptedBytes.slice(0, dataLength);
  const tag = encryptedBytes.slice(dataLength);
  return {
    iv,
    data,
    tag
  };
}
async function decrypt(encrypted, key) {
  const subtle = getSubtleCrypto();
  const combined = new Uint8Array(encrypted.data.byteLength + encrypted.tag.byteLength);
  combined.set(encrypted.data, 0);
  combined.set(encrypted.tag, encrypted.data.byteLength);
  try {
    const decryptedBuffer = await subtle.decrypt(
      {
        name: "AES-GCM",
        iv: encrypted.iv,
        tagLength: AES_TAG_LENGTH
      },
      key,
      combined
    );
    const decoder = new TextDecoder();
    return decoder.decode(decryptedBuffer);
  } catch {
    throw new Error("Decryption failed: integrity check or authentication tag mismatch. Data may be corrupted or key incorrect.");
  }
}
function uint8ArrayToBase64(bytes) {
  let binary = "";
  const len = bytes.byteLength;
  for (let i = 0; i < len; i++) {
    binary += String.fromCharCode(bytes[i]);
  }
  return btoa(binary);
}
function base64ToUint8Array(base64) {
  let normalized = base64.replace(/-/g, "+").replace(/_/g, "/");
  while (normalized.length % 4 !== 0) {
    normalized += "=";
  }
  const binary = atob(normalized);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i);
  }
  return bytes;
}
function uint8ArrayToBase64Url(bytes) {
  return uint8ArrayToBase64(bytes).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}
function base64UrlToUint8Array(base64url) {
  return base64ToUint8Array(base64url);
}
function stringToBase64Url(str) {
  const encoder = new TextEncoder();
  return uint8ArrayToBase64Url(encoder.encode(str));
}
function base64UrlToString(base64url) {
  const bytes = base64UrlToUint8Array(base64url);
  const decoder = new TextDecoder();
  return decoder.decode(bytes);
}

// src/crypto/serializer.ts
var INLINE_SECRET_REGEX = /%%(?:km|vg):v1:((?:(?:label|iv|data|tag)=[A-Za-z0-9_/\-+=]*:?)+)%%/g;
var CODE_BLOCK_SECRET_REGEX = /```(?:keymask|vaultguard)\s*\n([\s\S]*?)\n```/g;
function serializeInline(payload) {
  const parts = ["km:v1"];
  if (payload.label && payload.label.trim().length > 0) {
    const encodedLabel = stringToBase64Url(payload.label.trim());
    parts.push(`label=${encodedLabel}`);
  }
  const ivB64 = uint8ArrayToBase64Url(payload.encrypted.iv);
  const dataB64 = uint8ArrayToBase64Url(payload.encrypted.data);
  const tagB64 = uint8ArrayToBase64Url(payload.encrypted.tag);
  parts.push(`iv=${ivB64}`);
  parts.push(`data=${dataB64}`);
  parts.push(`tag=${tagB64}`);
  return `%%${parts.join(":")}%%`;
}
function parseInline(raw) {
  const trimmed = raw.trim();
  const isKm = trimmed.startsWith("%%km:v1:");
  const isVg = trimmed.startsWith("%%vg:v1:");
  if (!isKm && !isVg || !trimmed.endsWith("%%")) {
    return null;
  }
  const content = trimmed.slice(8, -2);
  const pairs = content.split(":");
  let label;
  let ivStr;
  let dataStr;
  let tagStr;
  for (const pair of pairs) {
    const eqIdx = pair.indexOf("=");
    if (eqIdx === -1) continue;
    const key = pair.slice(0, eqIdx).trim();
    const val = pair.slice(eqIdx + 1).trim();
    if (key === "label" && val) {
      try {
        label = base64UrlToString(val);
      } catch {
        label = val;
      }
    } else if (key === "iv") {
      ivStr = val;
    } else if (key === "data") {
      dataStr = val;
    } else if (key === "tag") {
      tagStr = val;
    }
  }
  if (!ivStr || !dataStr || !tagStr) {
    return null;
  }
  try {
    const iv = base64UrlToUint8Array(ivStr);
    const data = base64UrlToUint8Array(dataStr);
    const tag = base64UrlToUint8Array(tagStr);
    return {
      version: 1,
      label,
      iv,
      data,
      tag,
      rawText: trimmed,
      isCodeBlock: false
    };
  } catch {
    return null;
  }
}
function serializeCodeBlock(payload) {
  const lines = ["```keymask", "version: 1"];
  if (payload.isFile) {
    lines.push("type: file");
  }
  if (payload.label && payload.label.trim().length > 0) {
    lines.push(`label: ${payload.label.trim()}`);
  }
  const ivB64 = uint8ArrayToBase64(payload.encrypted.iv);
  const tagB64 = uint8ArrayToBase64(payload.encrypted.tag);
  const dataB64 = uint8ArrayToBase64(payload.encrypted.data);
  lines.push(`iv: ${ivB64}`);
  lines.push(`tag: ${tagB64}`);
  lines.push("data: |");
  const chunkSize = 64;
  for (let i = 0; i < dataB64.length; i += chunkSize) {
    lines.push(`  ${dataB64.slice(i, i + chunkSize)}`);
  }
  lines.push("```");
  return lines.join("\n");
}
function parseCodeBlock(raw) {
  const trimmed = raw.trim();
  let content = trimmed;
  if (trimmed.startsWith("```keymask") || trimmed.startsWith("```vaultguard")) {
    const startIdx = trimmed.indexOf("\n");
    const endIdx = trimmed.lastIndexOf("```");
    if (startIdx === -1 || endIdx <= startIdx) return null;
    content = trimmed.slice(startIdx + 1, endIdx).trim();
  }
  const lines = content.split("\n");
  let version = 1;
  let isFilePayload = false;
  let label;
  let ivStr;
  let tagStr;
  let inDataBlock = false;
  const dataChunks = [];
  for (const line of lines) {
    const trimmedLine = line.trim();
    if (trimmedLine.length === 0) continue;
    if (inDataBlock) {
      if (trimmedLine.startsWith("label:") || trimmedLine.startsWith("iv:") || trimmedLine.startsWith("tag:") || trimmedLine.startsWith("version:") || trimmedLine.startsWith("type:")) {
        inDataBlock = false;
      } else {
        dataChunks.push(trimmedLine);
        continue;
      }
    }
    if (trimmedLine.startsWith("version:")) {
      version = parseInt(trimmedLine.slice(8).trim(), 10) || 1;
    } else if (trimmedLine.startsWith("type:")) {
      const typeVal = trimmedLine.slice(5).trim().toLowerCase();
      if (typeVal === "file") {
        isFilePayload = true;
      }
    } else if (trimmedLine.startsWith("label:")) {
      label = trimmedLine.slice(6).trim();
    } else if (trimmedLine.startsWith("iv:")) {
      ivStr = trimmedLine.slice(3).trim();
    } else if (trimmedLine.startsWith("tag:")) {
      tagStr = trimmedLine.slice(4).trim();
    } else if (trimmedLine.startsWith("data:")) {
      const rest = trimmedLine.slice(5).trim();
      if (rest === "|") {
        inDataBlock = true;
      } else if (rest.length > 0) {
        dataChunks.push(rest);
      }
    }
  }
  const dataStr = dataChunks.join("");
  if (!ivStr || !dataStr || !tagStr) {
    return null;
  }
  try {
    const iv = base64ToUint8Array(ivStr);
    const data = base64ToUint8Array(dataStr);
    const tag = base64ToUint8Array(tagStr);
    return {
      version: version || 1,
      label,
      iv,
      data,
      tag,
      rawText: trimmed,
      isCodeBlock: true,
      isFilePayload
    };
  } catch {
    return null;
  }
}
function parseSecret(raw) {
  const trimmed = raw.trim();
  if (trimmed.startsWith("%%km:v1:") || trimmed.startsWith("%%vg:v1:")) {
    return parseInline(trimmed);
  }
  if (trimmed.startsWith("```keymask") || trimmed.startsWith("```vaultguard") || trimmed.includes("data: |")) {
    return parseCodeBlock(trimmed);
  }
  return null;
}
function isWholeFileEncrypted(content) {
  if (!content) return false;
  let trimmed = content.trim();
  if (trimmed.startsWith("---")) {
    const endFmIdx = trimmed.indexOf("\n---", 3);
    if (endFmIdx !== -1) {
      trimmed = trimmed.slice(endFmIdx + 4).trim();
    }
  }
  if ((trimmed.startsWith("```keymask") || trimmed.startsWith("```vaultguard")) && trimmed.endsWith("```")) {
    return true;
  }
  if ((trimmed.startsWith("%%km:v1:") || trimmed.startsWith("%%vg:v1:")) && trimmed.endsWith("%%") && !trimmed.slice(8, -2).includes("\n")) {
    return true;
  }
  return false;
}
function extractWholeFilePayload(content) {
  if (!content) return null;
  let trimmed = content.trim();
  if (trimmed.startsWith("---")) {
    const endFmIdx = trimmed.indexOf("\n---", 3);
    if (endFmIdx !== -1) {
      trimmed = trimmed.slice(endFmIdx + 4).trim();
    }
  }
  if (!isWholeFileEncrypted(trimmed)) {
    return null;
  }
  return parseSecret(trimmed);
}

